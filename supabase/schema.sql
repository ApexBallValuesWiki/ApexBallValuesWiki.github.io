-- PUBLIC VIEWS FOR AUDIT LOGS
create or replace view public.value_change_log_public as
  select id, slug, kind, old_value, new_value, changed_by, changed_at,
    case when public.is_owner() then changed_by_email else null end as changed_by_email
  from public.value_change_log;

create or replace view public.wiki_change_log_public as
  select id, slug, old_value, new_value, changed_by, changed_at,
    case when public.is_owner() then changed_by_email else null end as changed_by_email
  from public.wiki_change_log;

grant select on public.value_change_log_public to anon, authenticated;
grant select on public.wiki_change_log_public to anon, authenticated;

-- REALTIME WEBSOCKET REPLICATION PUBLICATION
alter table public.value_entries replica identity full;
alter table public.unit_wiki_overrides replica identity full;
alter table public.site_announcements replica identity full;

do $$
begin
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'value_entries') then
    alter publication supabase_realtime add table public.value_entries;
  end if;

  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'unit_wiki_overrides') then
    alter publication supabase_realtime add table public.unit_wiki_overrides;
  end if;

  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'site_announcements') then
    alter publication supabase_realtime add table public.site_announcements;
  end if;
end $$;
